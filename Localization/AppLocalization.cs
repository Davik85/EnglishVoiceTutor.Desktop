    private static readonly Lazy<IReadOnlyDictionary<string, AppLocalizedText>> TextByLanguageId = new(BuildTextByLanguageId);

    public static AppLocalizedText GetText(string? languageId)
    {
        var normalizedLanguageId = NormalizeLanguageId(languageId);
        return TextByLanguageId.Value.TryGetValue(normalizedLanguageId, out var text) ? text : TextByLanguageId.Value[InterfaceLanguageOptions.EnglishId];
    }

    public static SettingsLocalizedText GetSettingsText(string? languageId) => GetText(languageId).Settings;

    public static string GetLearnerUiText(string? languageId, string englishText)
    {
        var normalizedLanguageId = NormalizeLanguageId(languageId);
        return LearnerUiTextByLanguageId.TryGetValue(normalizedLanguageId, out var texts) && texts.TryGetValue(englishText, out var localizedText)
            ? localizedText
            : englishText;
    }

    public static LocalizedDisplayText GetTopicDisplayText(string? languageId, string title, string description)
    {
        return GetDisplayText(GetText(languageId).TopicDisplayTextByTitle, title, description);
    }

    public static LocalizedDisplayText GetSubtopicDisplayText(string? languageId, string title, string description)
    {
        return GetDisplayText(GetText(languageId).SubtopicDisplayTextByTitle, title, description);
    }

    public static string NormalizeLanguageId(string? languageId)
    {
        return NativeLanguageCatalog.GetByIdOrName(languageId).Id;
    }

    private static IReadOnlyDictionary<string, AppLocalizedText> BuildTextByLanguageId()
    {
        var result = new Dictionary<string, AppLocalizedText>(StringComparer.OrdinalIgnoreCase);
        foreach (var language in NativeLanguageCatalog.All)
        {
            var terms = TermsByLanguageId.TryGetValue(language.Id, out var localizedTerms) ? localizedTerms : EnglishTerms;
            result[language.Id] = CreateText(language.Id, terms);
        }
        return result;
    }

